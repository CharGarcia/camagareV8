-- 1) Restaurar los casilleros del catálogo que estén marcados como eliminados.
--    (Va en su propia sentencia: PostgreSQL no permite actualizar la misma fila
--     dos veces dentro de un mismo statement.)
UPDATE supercias_estructuras e
   SET eliminado = false, updated_at = NOW()
  FROM supercias_oficial o
 WHERE e.tipo = o.tipo AND e.codigo = o.codigo
   AND COALESCE(e.subcodigo, '') = o.subcodigo
   AND e.eliminado = true;

-- 2) Fijar el orden oficial. El nombre solo se completa si estaba vacío y las
--    fórmulas ya cargadas NO se tocan.
UPDATE supercias_estructuras e
   SET orden = o.orden,
       nombre = CASE WHEN COALESCE(e.nombre, '') = '' THEN o.nombre ELSE e.nombre END,
       updated_at = NOW()
  FROM supercias_oficial o
 WHERE e.tipo = o.tipo AND e.codigo = o.codigo
   AND COALESCE(e.subcodigo, '') = o.subcodigo
   AND e.eliminado = false;

-- 3) Insertar los casilleros del catálogo que no existen.
INSERT INTO supercias_estructuras (tipo, codigo, subcodigo, nombre, formula, orden, eliminado, created_at, updated_at, created_by, updated_by)
SELECT o.tipo, o.codigo, o.subcodigo, o.nombre, o.formula, o.orden, false, NOW(), NOW(), 1, 1
  FROM supercias_oficial o
 WHERE NOT EXISTS (SELECT 1 FROM supercias_estructuras e
                    WHERE e.tipo = o.tipo AND e.codigo = o.codigo
                      AND COALESCE(e.subcodigo, '') = o.subcodigo);

-- 4) Las columnas 30 y 31 del ECP (patrimonio atribuible a la controladora y
--    participación controladora) van en 0.00 salvo consolidación: sin fórmula.
UPDATE supercias_estructuras
   SET formula = NULL, updated_at = NOW()
 WHERE tipo = 'ECP' AND eliminado = false
   AND subcodigo IN ('30', '31') AND formula IS NOT NULL;

-- 5) Verificación: debe devolver ESF 376, ERI 246, ECP 320, EFE 83.
SELECT tipo, COUNT(*) AS casilleros
  FROM supercias_estructuras WHERE eliminado = false
 GROUP BY tipo ORDER BY tipo;

-- 6) Verificación: no debe devolver ninguna fila (claves repetidas).
SELECT tipo, codigo, COALESCE(subcodigo, '') AS subcodigo, COUNT(*) AS veces
  FROM supercias_estructuras WHERE eliminado = false
 GROUP BY 1, 2, 3 HAVING COUNT(*) > 1;

