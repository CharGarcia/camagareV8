       c.numero_ingreso, c.monto_total AS valor_nuevo, c.estado AS estado_nuevo, c.eliminado, c.tipo_ingreso,
       CASE WHEN m.id_destino IS NULL THEN '1. No se migró'
            WHEN c.id IS NULL         THEN '2. El ingreso del mapa ya no existe'
            WHEN c.eliminado          THEN '3. Migrado pero eliminado'
            WHEN (v.estado ILIKE '%anul%') <> (c.estado = 'anulado') THEN '4. Estado distinto'
            ELSE '5. Valor distinto' END AS caso
FROM viejo v
CROSS JOIN emp e
LEFT JOIN migracion_mysql_map m ON m.id_empresa = e.id AND m.entidad = 'ingresos' AND m.id_origen::text = v.id_ing::text
LEFT JOIN ingresos_cabecera c ON c.id = m.id_destino
WHERE m.id_destino IS NULL OR c.id IS NULL OR c.eliminado
   OR (v.estado ILIKE '%anul%') <> (c.estado = 'anulado')
   OR ROUND(v.valor - c.monto_total, 2) <> 0
ORDER BY caso, v.fecha;
