       CASE WHEN t.table_name IS NULL THEN 'FALTA LA TABLA' ELSE 'FALTA LA COLUMNA' END AS problema
FROM requeridas r
LEFT JOIN information_schema.tables t
       ON t.table_schema='public' AND t.table_name = r.tabla
LEFT JOIN information_schema.columns c
       ON c.table_schema='public' AND c.table_name = r.tabla AND c.column_name = r.columna
WHERE c.column_name IS NULL
ORDER BY 1, 2;
